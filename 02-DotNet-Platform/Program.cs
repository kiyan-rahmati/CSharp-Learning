// ------------------------------------------
// 1. The .NET Platform
// ------------------------------------------

// .NET is a development platform used to build
// and run different types of applications.

// ------------------------------------------
// 2. SDK (Software Development Kit)
// ------------------------------------------

// The SDK provides tools for developing applications.
// It includes the compiler, CLI, build tools, and templates.

// ------------------------------------------
// 3. Runtime
// ------------------------------------------

// The Runtime provides the environment required
// to execute .NET applications.

// ------------------------------------------
// 4. CLR (Common Language Runtime)
// ------------------------------------------

// The CLR manages the execution of .NET programs.

// It provides:
// - Memory Management
// - Garbage Collection
// - Exception Handling
// - Code Execution

// ------------------------------------------
// 5. BCL (Base Class Library)
// ------------------------------------------

// The BCL provides built-in libraries and functionality.

// Examples:
// - Strings
// - Collections
// - Files
// - Dates
// - Input and Output

// ------------------------------------------
// 6. Compiler
// ------------------------------------------

// The compiler translates C# source code
// into Intermediate Language (IL).

// ------------------------------------------
// 7. IL (Intermediate Language)
// ------------------------------------------

// IL is an intermediate code generated
// after compiling C# source code.

// ------------------------------------------
// 8. JIT (Just-In-Time Compiler)
// ------------------------------------------

// JIT translates IL into machine code
// during program execution.

// ------------------------------------------
// 9. .NET CLI
// ------------------------------------------

// CLI provides commands for managing .NET projects.

// Run these commands in the terminal:

// dotnet --version
// dotnet new console
// dotnet build
// dotnet run
// dotnet restore
// dotnet clean

// ------------------------------------------
// 10. Execution Flow
// ------------------------------------------

// C# Source Code
//       ↓
//    Compiler
//       ↓
// Intermediate Language (IL)
//       ↓
//      CLR
//       ↓
//      JIT
//       ↓
//  Machine Code
//       ↓
//    Execution

